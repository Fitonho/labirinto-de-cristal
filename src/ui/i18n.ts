export type StringKey = keyof (typeof strings)['pt'];

export function t(language: Language, key: StringKey): string {
  return strings[language][key];
}

/** A string with its {name} gaps filled in. */
export function tFilled(language: Language, key: StringKey, valuesByName: Record<string, string | number>): string {
  return t(language, key).replace(/\{(\w+)\}/g, (gap, name: string) => (name in valuesByName ? String(valuesByName[name]) : gap));
}

/** A level's name, or its number when it has none yet. */
export function levelNameFor(language: Language, levelId: string, levelOrder: number): string {
  const key = `levelName.${levelId}`;
  return key in strings[language] ? t(language, key as StringKey) : `${t(language, 'level')} ${levelOrder}`;
}

/** Portuguese for any Portuguese locale tag (pt, pt-BR, pt-PT), English otherwise. */
export function languageForLocale(localeTag: string | undefined): Language {
  if (!localeTag) return 'pt';
  return localeTag.toLowerCase().startsWith('pt') ? 'pt' : 'en';
}
